/** Section heading block shared by most sections. */
export function sectionHead({ id, eyebrow, title, intro = '', align = 'start', titleTag = 'h2' }) {
  const center = align === 'center' ? 'text-center mx-auto items-center' : '';
  return `
    <div class="section-head flex flex-col gap-5 ${center}" data-reveal-group>
      <p class="eyebrow" data-reveal-item>${esc(eyebrow)}</p>
      <${titleTag} id="${id}" class="h-section" data-reveal-item>${esc(title)}</${titleTag}>
      ${intro ? `<p class="lead max-w-2xl" data-reveal-item>${esc(intro)}</p>` : ''}
    </div>`;
}
