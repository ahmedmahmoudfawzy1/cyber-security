/** Escape text for safe HTML output. */
export function esc(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Wrap Latin/English text in <bdi> so trailing punctuation renders correctly
 * inside RTL paragraphs (e.g. "What is Cybersecurity?").
 */
export function en(text) {
  return `<bdi>${esc(text)}</bdi>`;
}

/** Zero-padded index: 1 -> "01". */
export function pad(n) {
  return String(n).padStart(2, '0');
}

/** Join an array of template results. */
export function join(items, fn) {
  return items.map(fn).join('');
}

